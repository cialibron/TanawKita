// One-off: looks up each barangay's center on OpenStreetMap (Nominatim) and writes src/data/barangayGeo.ts.
// Only public barangay names are sent. Nominatim allows 1 request per second, so this takes ~3 minutes.
// Usage: node scripts/geocode-barangays.mjs [path, default data/insights/21_barangay_master_lookup.csv]
import { readFileSync, writeFileSync } from 'node:fs'

const csvPath = process.argv[2] ?? 'data/insights/21_barangay_master_lookup.csv'
if (!csvPath) throw new Error('Pass the path to 21_barangay_master_lookup.csv')

const rows = readFileSync(csvPath, 'utf8').replace(/^﻿/, '').trim().split(/\r?\n/).slice(1)
const barangays = rows.map((line) => {
  const [code, , name] = line.split(',')
  return { code: code.trim(), name: name.trim() }
})

// Rough Davao City bounds, to reject matches elsewhere in the Philippines.
const inDavao = (lat, lng) => lat > 6.9 && lat < 7.65 && lng > 125.15 && lng < 125.75
const sleep = (ms) => new Promise((r) => setTimeout(r, ms))

async function lookup(query) {
  const url = `https://nominatim.openstreetmap.org/search?format=json&limit=5&countrycodes=ph&q=${encodeURIComponent(query)}`
  const res = await fetch(url, { headers: { 'User-Agent': 'TanawKita-prototype/0.1 (Ateneo de Davao student project)' } })
  if (!res.ok) throw new Error(`HTTP ${res.status}`)
  const hits = await res.json()
  const hit = hits.map((h) => [Number(h.lat), Number(h.lon)]).find(([lat, lng]) => inDavao(lat, lng))
  return hit ?? null
}

const found = {}
const missing = []
for (const b of barangays) {
  let point = null
  for (const q of [`${b.name}, Davao City`, `Barangay ${b.name}, Davao City`]) {
    try {
      point = await lookup(q)
    } catch (e) {
      console.error(`${b.code} ${b.name}: ${e.message}`)
    }
    await sleep(1100)
    if (point) break
  }
  if (point) found[b.code] = point.map((n) => Math.round(n * 1e5) / 1e5)
  else missing.push(`${b.code} ${b.name}`)
  process.stdout.write(point ? '.' : 'x')
}

const body = Object.entries(found)
  .map(([code, [lat, lng]]) => `  '${code}': [${lat}, ${lng}],`)
  .join('\n')
writeFileSync(
  'src/data/barangayGeo.ts',
  `// Generated by scripts/geocode-barangays.mjs from OpenStreetMap (Nominatim). Approximate barangay centers.\n` +
    `// Missing (no match inside Davao City): ${missing.length ? missing.join('; ') : 'none'}\n` +
    `export const BARANGAY_CENTERS: Record<string, [number, number]> = {\n${body}\n}\n`,
)
console.log(`\nFound ${Object.keys(found).length} of ${barangays.length}. Missing: ${missing.length}`)
if (missing.length) console.log(missing.join('\n'))
