// Writes src/data/labor.ts from 02_barangay_labor_digital_profile.csv (CBMS barangay aggregates, no personal records).
// Usage: node scripts/gen-labor.mjs [path, default data/insights/02_barangay_labor_digital_profile.csv]
import { readFileSync, writeFileSync } from 'node:fs'

const csvPath = process.argv[2] ?? 'data/insights/02_barangay_labor_digital_profile.csv'
if (!csvPath) throw new Error('Pass the path to 02_barangay_labor_digital_profile.csv')

const [header, ...lines] = readFileSync(csvPath, 'utf8').replace(/^﻿/, '').trim().split(/\r?\n/)
const cols = header.split(',')
const num = (row, name) => {
  const v = Number(row[cols.indexOf(name)])
  return Number.isFinite(v) ? v : 0
}

const entries = lines.map((line) => {
  const row = line.split(',')
  const code = row[cols.indexOf('barangay_code')].trim().padStart(3, '0')
  const fields = {
    population: num(row, 'population'),
    jobseekerPool: num(row, 'jobseeker_pool'),
    unemployed: num(row, 'unemployed'),
    underemployed: num(row, 'underemployed'),
    neetYouth: num(row, 'neet_youth'),
    tvetGrads: num(row, 'tvet_grads'),
    casualWorkers: num(row, 'casual_workers'),
    dailyPaid: num(row, 'daily_paid'),
    microBusinesses: num(row, 'msme_proxy_selfemp_employers'),
    households: num(row, 'households'),
    pctNoInternet: num(row, 'pct_hh_no_internet'),
    pctSmartphone: num(row, 'pct_hh_smartphone'),
  }
  return `  '${code}': ${JSON.stringify(fields).replace(/"(\w+)":/g, '$1: ')},`
})

writeFileSync(
  'src/data/labor.ts',
  `// Generated by scripts/gen-labor.mjs from 02_barangay_labor_digital_profile.csv. CBMS barangay aggregates only.\n` +
    `export interface BarangayLabor {\n  population: number\n  jobseekerPool: number\n  unemployed: number\n  underemployed: number\n` +
    `  neetYouth: number\n  tvetGrads: number\n  casualWorkers: number\n  dailyPaid: number\n  microBusinesses: number\n` +
    `  households: number\n  pctNoInternet: number\n  pctSmartphone: number\n}\n\n` +
    `export const BARANGAY_LABOR: Record<string, BarangayLabor> = {\n${entries.join('\n')}\n}\n`,
)
console.log(`Wrote ${entries.length} barangays`)
